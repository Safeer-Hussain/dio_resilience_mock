/// HTTP request and response models for resilience mocking.
library;

bool _deepEquals(Object? a, Object? b) {
  if (identical(a, b)) return true;
  if (a is Map && b is Map) {
    if (a.length != b.length) return false;
    for (final key in a.keys) {
      if (!b.containsKey(key)) return false;
      if (!_deepEquals(a[key], b[key])) return false;
    }
    return true;
  }
  if (a is List && b is List) {
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (!_deepEquals(a[i], b[i])) return false;
    }
    return true;
  }
  if (a is Set && b is Set) {
    if (a.length != b.length) return false;
    return a.every((element) => b.any((other) => _deepEquals(element, other)));
  }
  return a == b;
}

int _deepHashCode(Object? value) {
  if (value is Map) {
    return Object.hashAllUnordered(
      value.entries.map(
        (e) => Object.hash(_deepHashCode(e.key), _deepHashCode(e.value)),
      ),
    );
  }
  if (value is List) {
    return Object.hashAll(value.map(_deepHashCode));
  }
  if (value is Set) {
    return Object.hashAllUnordered(value.map(_deepHashCode));
  }
  return value.hashCode;
}

/// Immutable representation of an incoming HTTP request to the mock engine.
class MockHttpRequest {
  /// Creates a new [MockHttpRequest] instance.
  ///
  /// The [method] is automatically normalized to uppercase.
  MockHttpRequest({
    required String method,
    required this.path,
    Map<String, String> queryParameters = const {},
    Map<String, String> headers = const {},
    this.body,
  })  : method = method.toUpperCase(),
        queryParameters = Map.unmodifiable(queryParameters),
        headers = Map.unmodifiable(headers);

  /// The HTTP request method (e.g. GET, POST, PUT, DELETE), normalized uppercase.
  final String method;

  /// The target resource path (e.g. `/api/v1/orders`).
  final String path;

  /// Unmodifiable map of parsed query parameters.
  final Map<String, String> queryParameters;

  /// Unmodifiable map of HTTP headers.
  final Map<String, String> headers;

  /// Optional payload or request body.
  final Object? body;

  /// Unique cache key composed of `$method:$path`.
  String get cacheKey => '$method:$path';

  /// Creates a copy of this request with the given fields replaced.
  MockHttpRequest copyWith({
    String? method,
    String? path,
    Map<String, String>? queryParameters,
    Map<String, String>? headers,
    Object? body,
  }) {
    return MockHttpRequest(
      method: method ?? this.method,
      path: path ?? this.path,
      queryParameters: queryParameters ?? this.queryParameters,
      headers: headers ?? this.headers,
      body: body ?? this.body,
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is MockHttpRequest &&
        other.method == method &&
        other.path == path &&
        _deepEquals(other.queryParameters, queryParameters) &&
        _deepEquals(other.headers, headers) &&
        _deepEquals(other.body, body);
  }

  @override
  int get hashCode => Object.hash(
        method,
        path,
        _deepHashCode(queryParameters),
        _deepHashCode(headers),
        _deepHashCode(body),
      );

  @override
  String toString() {
    return 'MockHttpRequest('
        'method: $method, '
        'path: $path, '
        'queryParameters: $queryParameters, '
        'headers: $headers, '
        'body: $body)';
  }
}

/// Immutable representation of an HTTP response returned by the mock engine.
class MockHttpResponse {
  /// Creates a new [MockHttpResponse] instance.
  MockHttpResponse({
    this.statusCode = 200,
    this.data,
    Map<String, String> headers = const {},
    this.simulatedLatency = Duration.zero,
    this.isFromOfflineCache = false,
    this.isFaultInjected = false,
  }) : headers = Map.unmodifiable(headers);

  /// HTTP status code (e.g. 200, 201, 404, 503).
  final int statusCode;

  /// Response body or payload.
  final Object? data;

  /// Unmodifiable map of response headers.
  final Map<String, String> headers;

  /// Simulated latency delay applied prior to serving this response.
  final Duration simulatedLatency;

  /// Whether this response was served from the local offline cache fallback.
  final bool isFromOfflineCache;

  /// Whether this response was generated by active fault injection or chaos simulation.
  final bool isFaultInjected;

  /// Whether the HTTP status code represents a success (200 through 299).
  bool get isSuccess => statusCode >= 200 && statusCode < 300;

  /// Creates a copy of this response with the given fields replaced.
  MockHttpResponse copyWith({
    int? statusCode,
    Object? data,
    Map<String, String>? headers,
    Duration? simulatedLatency,
    bool? isFromOfflineCache,
    bool? isFaultInjected,
  }) {
    return MockHttpResponse(
      statusCode: statusCode ?? this.statusCode,
      data: data ?? this.data,
      headers: headers ?? this.headers,
      simulatedLatency: simulatedLatency ?? this.simulatedLatency,
      isFromOfflineCache: isFromOfflineCache ?? this.isFromOfflineCache,
      isFaultInjected: isFaultInjected ?? this.isFaultInjected,
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is MockHttpResponse &&
        other.statusCode == statusCode &&
        _deepEquals(other.data, data) &&
        _deepEquals(other.headers, headers) &&
        other.simulatedLatency == simulatedLatency &&
        other.isFromOfflineCache == isFromOfflineCache &&
        other.isFaultInjected == isFaultInjected;
  }

  @override
  int get hashCode => Object.hash(
        statusCode,
        _deepHashCode(data),
        _deepHashCode(headers),
        simulatedLatency,
        isFromOfflineCache,
        isFaultInjected,
      );

  @override
  String toString() {
    return 'MockHttpResponse('
        'statusCode: $statusCode, '
        'data: $data, '
        'headers: $headers, '
        'simulatedLatency: $simulatedLatency, '
        'isFromOfflineCache: $isFromOfflineCache, '
        'isFaultInjected: $isFaultInjected)';
  }
}
